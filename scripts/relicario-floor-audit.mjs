import { chromium } from "playwright";
const browser=await chromium.launch({headless:true,args:["--use-gl=angle","--use-angle=swiftshader","--enable-webgl","--autoplay-policy=no-user-gesture-required"]});
const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
const errors=[];page.on("pageerror",e=>errors.push(e.message));
try {
 const url="http://127.0.0.1:8765/tehiceesto/ar-pareja-auditoria/";
 const res=await page.goto(url,{waitUntil:"domcontentloaded",timeout:35000});
 if(res.status()!==200)throw Error("Demo HTTP "+res.status());
 await page.locator("#sceneLoading.gone").waitFor({state:"attached",timeout:35000});
 const data=await page.evaluate(async()=>{
  const mod=await import("./relicario-xr.js");
  const url=new URL("./relicario.glb",location.href).href;
  const c=new mod.RelicarioSpatialAR({overlay:document.getElementById("arOverlay"),modelUrl:url});
  const asset=await c.loadPromise;
  const three=await import("three");
  const bbox=new three.Box3().setFromObject(asset.model);
  const box=bbox.getSize(new three.Vector3());
  const orientationOk=box.y>box.x&&box.y>box.z&&bbox.min.y>-.02&&bbox.min.y<.02;
  if(!orientationOk)throw Error("GLB is not upright and standing on base: "+JSON.stringify({size:box.toArray(),min:bbox.min.toArray()}));
  if(asset.meshes<100)throw Error("Art asset replaced by prototype meshes: "+asset.meshes);
  const basePose={transform:{position:{x:0,y:0,z:-.8},orientation:{x:0,y:0,z:0,w:1}}};
  const wallPose={transform:{position:{x:0,y:0,z:-.8},orientation:{x:0,y:0,z:Math.sqrt(.5),w:Math.sqrt(.5)}}};
  const farPose={transform:{position:{x:0,y:0,z:-5},orientation:{x:0,y:0,z:0,w:1}}};
  const reference={};
  const viewer={transform:{position:{x:0,y:1.6,z:0}}};
  const floor={getPose:()=>basePose,createAnchor:async()=>({})};
  const wall={getPose:()=>wallPose};
  const far={getPose:()=>farPose};
  const frame={getHitTestResults:()=>[wall,far,floor]};
  const picked=mod.chooseFloorHit(frame,{source:1},reference,viewer);
  if(picked?.result!==floor)throw Error("Floor detector selected wall, distant point or no surface");
  if(mod.chooseFloorHit({getHitTestResults:()=>[wall,far]},1,reference,viewer))throw Error("Floor scanner accepted wall/distant plane");
  const fakeFix=await c.fix();
  if(fakeFix!==false||c.stage!=="inactive")throw Error("Invisible AR placement incorrectly accepted");
  c.adjustSize(.05);
  if(c.width<.44)throw Error("size control broken");
  if(!Array.isArray([box.x,box.y,box.z])||!Number.isFinite(box.y))throw Error("bad bounds");
  return {meshCount:asset.meshes,height:+box.y.toFixed(2),baseY:+bbox.min.y.toFixed(3),floorDistance:+picked.d.toFixed(2),fixWithoutPlane:fakeFix,glbSource:url};
 });
 console.log("PASS GLB stays upright on real floor after Z-up conversion",JSON.stringify(data));
 console.log("PASS horizontal hit-test rejects walls and unreachable surfaces");
 console.log("PASS fix is denied until real plane is found");
 await page.getByRole("button",{name:/DESCUBRIR EL ÚLTIMO REGALO/i}).click();
 await page.locator("#entryOverlay").waitFor({state:"detached",timeout:5000});
 await page.locator("#arBtn").click();
 await page.locator("#arDialog:visible").waitFor({timeout:4000});
 if(await page.locator("#arPlace").isEnabled())throw Error("Fix enabled before XR floor scan");
 if(!await page.locator("#arDiagnostic").count())throw Error("Missing runtime diagnostic/status");
 await page.screenshot({path:"visual-smoke/relicario/floor-placement-entry.png",fullPage:true});
 if(errors.length)throw Error("JS errors: "+errors.join(","));
 console.log("PASS buyer sees floor-first placement guidance and inactive fix button");
}finally{await browser.close()}
console.log("RELICARIO_FLOOR_SCAN_AUDIT_PASSED");
