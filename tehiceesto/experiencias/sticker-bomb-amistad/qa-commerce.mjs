import {chromium} from "playwright";
import assert from "node:assert/strict";
const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
const host="https://tehiceesto.com";
try{
 const p=await browser.newPage({viewport:{width:393,height:850},isMobile:true,hasTouch:true});
 const errors=[];p.on("pageerror",e=>errors.push(e.message));
 const d=await p.goto(host+"/experiencias/sticker-bomb-amistad",{waitUntil:"domcontentloaded",timeout:60000});
 assert.equal(d.status(),200,"model endpoint");
 assert.equal(await p.getByRole("button",{name:/Abrir nuestro expediente/}).count(),1);
 await p.getByRole("button",{name:/Abrir nuestro expediente/}).click();
 assert.equal(await p.locator(".sticker").count(),12);
 assert.equal(await p.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2),false);
 const edit=await browser.newPage({viewport:{width:393,height:850},isMobile:true,hasTouch:true});
 const editErrors=[];edit.on("pageerror",e=>editErrors.push(e.message));
 const r=await edit.goto(host+"/experiencias/sticker-bomb-amistad/editar",{waitUntil:"load",timeout:60000});
 assert.equal(r.status(),200,"editor path");
 await edit.waitForTimeout(2500);
 assert.equal(await edit.locator("#studio:not(.hidden)").count(),0,"unauthenticated editor must be locked");
 assert.equal(await edit.locator("#login:not(.hidden)").count(),1,"login must be available");
 assert.equal(await edit.locator("#magic-button").count(),1);
 await edit.locator("#magic-button").click();
 assert.match(await edit.locator("#status").innerText(),/correo|Escrib/i);
 const buy=await browser.newPage({viewport:{width:393,height:850},isMobile:true,hasTouch:true});
 const buyErrors=[];buy.on("pageerror",e=>buyErrors.push(e.message));
 const b=await buy.goto(host+"/comprar/sticker-bomb-amistad",{waitUntil:"domcontentloaded",timeout:60000});
 assert.equal(b.status(),200,"checkout path");
 assert.match(await buy.locator(".price").innerText(),/25\.000/);
 assert.equal(await buy.locator('#form input[type="email"]').count(),1);
 assert.match(await buy.locator("body").innerText(),/Mercado Pago/);
 assert.equal(await buy.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2),false);
 const secret=await browser.newPage({viewport:{width:393,height:850},isMobile:true,hasTouch:true});
 const bad=await secret.goto(host+"/experiencias/sticker-bomb-amistad?gift=000000000000000000",{waitUntil:"domcontentloaded",timeout:60000});
 assert.equal(bad.status(),200);
 await secret.getByRole("status").filter({hasText:/no está disponible|Preparando/i}).first().waitFor({timeout:25000});
 await secret.waitForTimeout(2000);
 assert.ok(await secret.evaluate(()=>[...document.querySelectorAll('[role="status"]')].some(e=>/no está disponible|no es válido/.test(e.textContent||""))),"unapproved gift must not expose a personalized story");
 assert.deepEqual(errors,[],"model JS errors");
 assert.deepEqual(editErrors,[],"editor JS errors");
 assert.deepEqual(buyErrors,[],"checkout JS errors");
 console.log("STICKER_BOMB_COMMERCE_PASS",JSON.stringify({demoStatus:d.status(),editorStatus:r.status(),checkoutStatus:b.status(),locked:true,price:"ARS 25000",mobileWidth:393}));
}finally{await browser.close()}
